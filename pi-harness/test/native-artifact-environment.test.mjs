import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { inspectAsar } from '../package-dmg/asar.mjs';
import { nativeArtifactEnvironmentFixture as fixture, replayNativeArtifactBinding, replayNativeArtifactBridge,
  replayNativeArtifactBindingFromInfo, replayNativeSidebarConversation, replayNativeFinalEnvironment,
  replayNativeProjectDetailPanelOptions } from './fixtures/native-artifact-environment-592.replay.mjs';

const localInfo = { id: 'pi-native-conversation', title: 'Pi local task', harnessId: 'pi', transport: 'local', conversationOrigin: 'local',
  cwd: '/Users/test/WorkBuddy/2026-10-28/task-1', space: { cwd: '/Users/test/WorkBuddy/2026-10-28/task-1', name: 'task-1', autoGenerated: true } };

test('exact environment slices pin native source and public project-page forceCloud callsite', () => {
  assert.equal(fixture.artifactSHA256, '0b79c0358c129749bc3355f52bbae13f115577ab37c082a76dfdc54f66fd3f79');
  for (const slice of fixture.slices) {
    assert.equal(createHash('sha256').update(slice.source).digest('hex'), slice.sha256);
    assert.equal(Buffer.byteLength(slice.source), slice.range.end - slice.range.start);
  }
  assert.match(fixture.slices.find(value => value.name === 'projectDetailPanelImport').source, /t as Gc.*detail-panel-wrapper-XXvjMNBg/);
  assert.equal(replayNativeProjectDetailPanelOptions().forceCloudEnvironment, true);
});

test('legacy Pi runtimeId forces cloud despite transport local; removing only that field restores native local host', () => {
  const legacy = { ...localInfo, runtimeId: localInfo.id }, cloud = replayNativeArtifactBinding(legacy);
  assert.equal(cloud.environmentType, 'cloud'); assert.equal(replayNativeFinalEnvironment(cloud), 'cloud');
  const host = replayNativeArtifactBinding(localInfo); assert.equal(host.environmentType, 'local');
  assert.equal(host.origin.taskId, localInfo.id); assert.equal(host.workspaceCwd, localInfo.cwd);
  assert.equal(replayNativeFinalEnvironment(host), 'local');
  assert.equal(replayNativeArtifactBridge(localInfo).environmentType, 'local');
});

test('actual info-to-sidebar mapping reads space.cwd and does not invent runtimeId from the conversation id', () => {
  const { cwd: _cwd, ...info } = localInfo, before = structuredClone(info), sidebar = replayNativeSidebarConversation(info);
  assert.equal(sidebar.id, info.id); assert.equal(sidebar.cwd, info.space.cwd); assert.equal(sidebar.transport, 'local');
  assert.equal(sidebar.runtimeId, undefined);
  const host = replayNativeArtifactBindingFromInfo(info, { scopeKey: 'actual-info-scope' });
  assert.equal(host.environmentType, 'local'); assert.equal(host.workspaceCwd, info.space.cwd); assert.equal(host.origin.taskId, info.id);
  assert.equal(host.scopeKey, 'actual-info-scope'); assert.equal(replayNativeFinalEnvironment(host), 'local');
  assert.deepEqual(info, before);
  assert.equal(replayNativeArtifactBindingFromInfo({ ...info, runtimeId: info.id }).environmentType, 'cloud');
});

test('native cloud runtime/transport, workspace, project sandbox and project-page policies remain cloud', () => {
  for (const info of [{ ...localInfo, runtimeId: 'real-cloud-runtime' }, { ...localInfo, transport: 'cloud' },
    { ...localInfo, cwd: '/workspace' }, { ...localInfo, cwd: '/workspace/nested/task' }]) {
    assert.equal(replayNativeArtifactBinding(info).environmentType, 'cloud');
    assert.equal(replayNativeArtifactBridge(info).environmentType, 'cloud');
  }
  for (const options of [{ forceCloud: true }, { projectSandbox: 'sandbox-a', routeProjectId: 'project-a' }, { projectDetailPage: true }]) {
    const host = replayNativeArtifactBinding(localInfo, options);
    assert.equal(host.environmentType, 'cloud'); assert.equal(replayNativeFinalEnvironment(host, options), 'cloud');
  }
  const injected = { environmentType: 'cloud', origin: { taskId: 'injected' } };
  assert.equal(replayNativeArtifactBridge(localInfo, { injectedHost: injected }), injected);
  assert.equal(replayNativeFinalEnvironment({ environmentType: 'local', isProjectSession: true, hasProjectSandbox: true }), 'cloud');
});

test('missing adapter environment does not fabricate local; ordinary non-workspace paths and home context use native fallback', () => {
  assert.equal(replayNativeArtifactBinding(localInfo, { adapter: {} }).environmentType, undefined);
  assert.equal(replayNativeArtifactBinding({ ...localInfo, cwd: '/project/local-files' }).environmentType, 'local');
  assert.equal(replayNativeArtifactBinding(localInfo, { homeContext: { isHome: true, cwd: '/workspace/new' } }).environmentType, 'cloud');
});

test('all environment fixture slices exactly match the original ASAR', { skip: !process.env.NATIVE_PREVIEW_TEST_ASAR }, () => {
  const archive = inspectAsar(process.env.NATIVE_PREVIEW_TEST_ASAR);
  for (const slice of fixture.slices) {
    const original = archive.read(slice.member);
    assert.equal(createHash('sha256').update(original).digest('hex'), slice.memberSHA256);
    assert.deepEqual(original.subarray(slice.range.start, slice.range.end), Buffer.from(slice.source));
  }
});
