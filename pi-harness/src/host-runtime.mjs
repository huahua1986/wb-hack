import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';

export class PiHostRuntime {
  constructor(adapter, { stateDir } = {}) {
    this.adapter = adapter; this.listeners = new Set(); this.sequence = 0; this.recentEvents = []; this.closed = false;
    this.filename = path.join(stateDir, 'ui.json');
    this.previewStatusFile = path.join(stateDir, 'preview-status.json');
    this.previewCounters = {};
    this.uiState = { active: false, activeThreadId: null, selectedHarnessId: adapter.id };
    try {
      if (!fs.lstatSync(this.filename).isFile() || fs.lstatSync(this.filename).isSymbolicLink()) throw Error('Invalid UI state file');
      const value = JSON.parse(fs.readFileSync(this.filename, 'utf8'));
      if (typeof value.active === 'boolean' && (value.activeThreadId === null || typeof value.activeThreadId === 'string')) this.uiState = { ...this.uiState, ...value, selectedHarnessId: adapter.id };
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
    this.unsubscribe = adapter.subscribe(event => {
      const next = { ...event, seq: ++this.sequence, timestamp: new Date().toISOString() };
      this.recentEvents.push(next); if (this.recentEvents.length > 100) this.recentEvents.shift();
      for (const listener of this.listeners) { try { listener(structuredClone(next)); } catch {} }
    });
  }
  subscribe(listener) { this.listeners.add(listener); return () => this.listeners.delete(listener); }
  snapshot() { return structuredClone({ version: 1, closed: this.closed, defaultHarnessId: this.adapter.id, uiState: this.uiState, harnesses: [this.adapter.snapshot()], activeInteractions: [], recentEvents: this.recentEvents }); }
  async dispatch(method, params = {}) {
    if (this.closed) throw Error('Pi Host is closed');
    if (!params || typeof params !== 'object' || Array.isArray(params)) throw Error('Invalid Host parameters');
    const string = (key, max = 4096) => { const value = params[key]; if (typeof value !== 'string' || !value.trim() || value.length > max) throw Error(`Invalid ${key}`); return value; };
    if (params.harnessId !== undefined && params.harnessId !== this.adapter.id) throw Error('Unknown harness');
    if (['runtime.snapshot', 'thread.list', 'thread.create', 'thread.model.set', 'thread.context.window.set', 'turn.start'].includes(method)
      && typeof this.adapter.refreshOfficialModels === 'function') {
      // The authoritative daemon can finish starting after the renderer. Never
      // publish a guessed official catalog or create a thread from stale rights.
      await this.adapter.refreshOfficialModels();
    }
    switch (method) {
      case 'runtime.snapshot': return this.snapshot();
      case 'expert.resolve': {
        if (Object.keys(params).some(key => !['expert'].includes(key))) throw Error('Unknown expert resolution field');
        return { expert: await this.adapter.resolveExpertSelection({ expert: params.expert }) };
      }
      case 'runtime.preview.note': {
        const reasons = ['event-sent', 'mounted', 'event', 'matched', 'dirty-skipped', 'unknown-skipped', 'stale-skipped', 'reloaded', 'read-failed', 'size-skipped',
          'nonlocal-skipped', 'extension-skipped', 'session-skipped', 'content-skipped', 'reader-skipped', 'probe-skipped', 'url-skipped', 'ref-skipped'];
        if (Object.keys(params).some(key => !['reason'].includes(key)) || !reasons.includes(params.reason)) throw Error('Invalid preview diagnostic');
        const filename = this.previewStatusFile;
        const parent = fs.lstatSync(path.dirname(filename));
        if (!parent.isDirectory() || parent.isSymbolicLink() || parent.mode & 0o077
          || process.getuid && parent.uid !== process.getuid()) throw Error('Invalid private diagnostic directory');
        try {
          const stat = fs.lstatSync(filename);
          if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1) throw Error('Invalid preview diagnostic file');
        } catch (cause) { if (cause.code !== 'ENOENT') throw cause; }
        this.previewCounters[params.reason] = Math.min(100000, (this.previewCounters[params.reason] ?? 0) + 1);
        const temporary = filename + '.' + randomUUID();
        try {
          fs.writeFileSync(temporary, JSON.stringify({ version: 1, counters: this.previewCounters, updatedAt: new Date().toISOString() }), { mode: 0o600, flag: 'wx' });
          fs.renameSync(temporary, filename);
        } finally { if (fs.existsSync(temporary)) fs.unlinkSync(temporary); }
        return { recorded: true };
      }
      case 'harness.list': return { harnesses: [this.adapter.describe()] };
      case 'thread.list': return { threads: await this.adapter.listThreads() };
      case 'thread.create': {
        if (params.workspaceAutoGenerated !== undefined && typeof params.workspaceAutoGenerated !== 'boolean') throw Error('Invalid workspace metadata');
        return { thread: await this.adapter.createThread({ title: params.title, cwd: params.cwd,
          ...(params.approvalMode === undefined ? {} : { approvalMode: string('approvalMode', 16) }),
          ...(params.model === undefined ? {} : { model: string('model', 256) }),
          ...(params.workspaceAutoGenerated === undefined ? {} : { workspaceAutoGenerated: params.workspaceAutoGenerated }) }) };
      }
      case 'thread.delete': return this.adapter.deleteThread(string('threadId'));
      case 'thread.rename': return { thread: await this.adapter.renameThread({ threadId: string('threadId'), title: string('title', 256) }) };
      case 'thread.model.set': return { thread: await this.adapter.setModel({ threadId: string('threadId'), model: string('model') }) };
      case 'thread.approval.set': return { thread: await this.adapter.setApprovalMode({ threadId: string('threadId'), approvalMode: string('approvalMode', 16) }) };
      case 'thread.context.usage': return { summary: await this.adapter.refreshContextUsage({ threadId: string('threadId') }) };
      case 'thread.context.window.set': {
        if (params.contextWindow !== null && !Number.isSafeInteger(params.contextWindow)) throw Error('Invalid contextWindow');
        return { thread: await this.adapter.setContextWindow({ threadId: string('threadId'), contextWindow: params.contextWindow }) };
      }
      case 'thread.execution.settings.set': {
        if (Object.keys(params).some(k => !['harnessId', 'threadId', 'thoughtLevel', 'preMessageCompactPct'].includes(k))) throw Error('Unknown execution setting');
        return { thread: await this.adapter.setExecutionSettings({ threadId: string('threadId'),
          ...(Object.hasOwn(params, 'thoughtLevel') ? { thoughtLevel: params.thoughtLevel } : {}),
          ...(Object.hasOwn(params, 'preMessageCompactPct') ? { preMessageCompactPct: params.preMessageCompactPct } : {}) }) };
      }
      case 'thread.compact': return this.adapter.compactThread({ threadId: string('threadId'),
        ...(params.customInstructions === undefined ? {} : { customInstructions: string('customInstructions', 8192) }) });
      case 'thread.files': return this.adapter.fileResources({ threadId: string('threadId'),
        ...(params.detailRef === undefined ? {} : { detailRef: string('detailRef', 256) }) });
      case 'thread.checkpoint.read': return this.adapter.checkpointRead({ threadId: string('threadId'), turnId: string('turnId', 256) });
      case 'thread.rewind': return this.adapter.rewindThread({ threadId: string('threadId'), turnId: string('turnId', 256) });
      case 'thread.office.restore': return this.adapter.restoreOfficeFiles({ threadId: string('threadId'), turnId: string('turnId', 256) });
      case 'thread.context.set': {
        if (Object.keys(params).some(key => !['harnessId', 'threadId', 'expert', 'connectors'].includes(key))) throw Error('Unknown context field');
        return { thread: await this.adapter.setNativeContext({ threadId: string('threadId'),
          ...(params.expert === undefined ? {} : { expert: params.expert }),
          ...(params.connectors === undefined ? {} : { connectors: params.connectors }) }) };
      }
      case 'turn.start': {
        if (params.promptContentBlocks !== undefined && (!Array.isArray(params.promptContentBlocks) || params.promptContentBlocks.length > 64)) throw Error('Invalid input blocks');
        if (params.skills !== undefined && (!Array.isArray(params.skills) || params.skills.length > 8)) throw Error('Invalid skills');
        const prompt = params.prompt === '' && params.promptContentBlocks?.length ? '' : string('prompt', 60000);
        return { turn: await this.adapter.startTurn({ threadId: string('threadId'), prompt,
          ...(params.promptContentBlocks === undefined ? {} : { promptContentBlocks: params.promptContentBlocks }),
          ...(params.skills === undefined ? {} : { skills: params.skills }),
          ...(params.model === undefined ? {} : { model: string('model', 256) }) }) };
      }
      case 'turn.cancel': return { turn: await this.adapter.cancelTurn({ threadId: string('threadId'), turnId: params.turnId }) };
      case 'interaction.respond': return this.adapter.respondInteraction(params);
      case 'ui.snapshot': return { uiState: structuredClone(this.uiState) };
      case 'ui.update': {
        if (Object.keys(params).some(k => !['active', 'activeThreadId', 'selectedHarnessId', 'approvalPreferenceSeed'].includes(k))) throw Error('Unknown UI field');
        if (params.approvalPreferenceSeed !== undefined && !['pi-040-auto', 'pi-040-manual'].includes(params.approvalPreferenceSeed)) throw Error('Invalid approval preference seed');
        if (params.active !== undefined && typeof params.active !== 'boolean') throw Error('Invalid active state');
        if (params.activeThreadId !== undefined && params.activeThreadId !== null && typeof params.activeThreadId !== 'string') throw Error('Invalid active thread');
        if (params.selectedHarnessId !== undefined && params.selectedHarnessId !== null && params.selectedHarnessId !== this.adapter.id) throw Error('Unknown harness');
        this.uiState = { ...this.uiState, ...params };
        const temp = this.filename + '.' + randomUUID();
        try { fs.writeFileSync(temp, JSON.stringify(this.uiState), { mode: 0o600, flag: 'wx' }); fs.renameSync(temp, this.filename); }
        finally { if (fs.existsSync(temp)) fs.unlinkSync(temp); }
        return { uiState: structuredClone(this.uiState) };
      }
      default: throw Error('Unsupported Pi Host method');
    }
  }
  async close() { if (this.closed) return; this.closed = true; this.unsubscribe(); this.listeners.clear(); await this.adapter.close(); }
}
