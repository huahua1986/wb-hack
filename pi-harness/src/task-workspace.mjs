import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const MAX_ATTEMPTS = 100;
const issue = (code, message) => Object.assign(new Error(message), { code });

export function defaultTaskWorkspaceRoot(homeDir = os.homedir()) {
  if (typeof homeDir !== 'string' || !path.isAbsolute(homeDir)) throw issue('TASK_WORKSPACE_INVALID', '用户主目录必须是绝对路径。');
  return path.join(homeDir, 'WorkBuddy');
}

export function formatTaskWorkspaceTimestamp(date) {
  if (!(date instanceof Date) || !Number.isFinite(date.getTime())) throw issue('TASK_WORKSPACE_INVALID', '任务日期无效。');
  const year = date.getFullYear();
  if (year < 0 || year > 9999) throw issue('TASK_WORKSPACE_INVALID', '任务日期超出支持范围。');
  const pad = value => String(value).padStart(2, '0');
  return `${String(year).padStart(4, '0')}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}-${pad(date.getHours())}-${pad(date.getMinutes())}-${pad(date.getSeconds())}`;
}

function checkedPath(value, { root = false } = {}) {
  if (typeof value !== 'string' || !value || value !== value.trim() || value.length > 8192 ||
      !path.isAbsolute(value) || /[\x00-\x1f\\]/.test(value) || value.split('/').some(part => part === '.' || part === '..') ||
      /[{}]/.test(value) || /%[A-Za-z_][A-Za-z0-9_]*%/.test(value) || /(?:^|\/)~(?:\/|$)/.test(value)) {
    throw issue('TASK_WORKSPACE_INVALID', '工作目录必须是已展开的本地绝对路径，且不能包含路径跳转。');
  }
  const resolved = path.resolve(value);
  if (root && resolved === path.parse(resolved).root) throw issue('TASK_WORKSPACE_INVALID', '不能把文件系统根目录作为自动任务根目录。');
  return resolved;
}

function sameDirectory(stat, snapshot) {
  return stat.isDirectory() && !stat.isSymbolicLink() && stat.dev === snapshot.dev && stat.ino === snapshot.ino;
}

function directoryTree(filename, { create = false } = {}) {
  const chain = [];
  let current = path.parse(filename).root;
  for (const part of ['', ...filename.slice(current.length).split(path.sep).filter(Boolean)]) {
    if (part) current = path.join(current, part);
    let stat;
    try { stat = fs.lstatSync(current); }
    catch (error) {
      if (!create || error.code !== 'ENOENT') throw error;
      try { fs.mkdirSync(current, { mode: 0o700 }); }
      catch (error) { if (error.code !== 'EEXIST') throw error; }
      stat = fs.lstatSync(current);
    }
    if (stat.isSymbolicLink() || !stat.isDirectory()) throw issue('TASK_WORKSPACE_UNSAFE', '工作目录包含符号链接或非目录路径。');
    chain.push({ path: current, dev: stat.dev, ino: stat.ino });
  }
  if (fs.realpathSync(filename) !== filename) throw issue('TASK_WORKSPACE_UNSAFE', '工作目录不是其规范安装路径。');
  return chain;
}

function assertSameTree(filename, chain) {
  for (const snapshot of chain) {
    if (!sameDirectory(fs.lstatSync(snapshot.path), snapshot)) throw issue('TASK_WORKSPACE_CHANGED', '工作目录在分配期间发生变化，请重试。');
  }
  if (fs.realpathSync(filename) !== filename) throw issue('TASK_WORKSPACE_CHANGED', '工作目录在分配期间发生变化，请重试。');
}

// Called only when creating a new task. Reopening a persisted task must reuse its saved cwd.
export async function allocateTaskWorkspace({ cwd, rootDir, now = () => new Date() } = {}) {
  try {
    if (cwd !== undefined && cwd !== null && cwd !== '') {
      directoryTree(checkedPath(cwd));
      return { cwd, workspaceAutoGenerated: false, created: false };
    }
    const root = checkedPath(rootDir === undefined ? defaultTaskWorkspaceRoot() : rootDir, { root: true });
    if (typeof now !== 'function') throw issue('TASK_WORKSPACE_INVALID', '任务时钟无效。');
    const instant = now();
    formatTaskWorkspaceTimestamp(instant);
    const chain = directoryTree(root, { create: true });
    for (let attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
      assertSameTree(root, chain);
      const name = formatTaskWorkspaceTimestamp(new Date(instant.getTime() + attempt * 1000));
      const candidate = path.join(root, name);
      try { fs.mkdirSync(candidate, { mode: 0o700 }); }
      catch (error) {
        if (error.code === 'EEXIST') continue;
        throw error;
      }
      assertSameTree(root, chain);
      const stat = fs.lstatSync(candidate);
      if (!stat.isDirectory() || stat.isSymbolicLink() || fs.realpathSync(candidate) !== candidate) {
        throw issue('TASK_WORKSPACE_CHANGED', '新任务目录在分配期间发生变化，请重试。');
      }
      return { cwd: candidate, workspaceAutoGenerated: true, created: true };
    }
    throw issue('TASK_WORKSPACE_EXHAUSTED', '同一时间段的任务目录已用满，请稍后创建任务。');
  } catch (error) {
    if (typeof error?.code === 'string' && error.code.startsWith('TASK_WORKSPACE_')) throw error;
    throw issue('TASK_WORKSPACE_UNAVAILABLE', '无法分配任务工作目录，请确认路径存在且可写。');
  }
}
