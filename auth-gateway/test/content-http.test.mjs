import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { startGateway, completeLogin } from './helpers.mjs';
import { seedPrivateContent } from '../scripts/seed-private-content.mjs';

const post = token => ({ method: 'POST', headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: '{}' });
const payload = res => res.json();

test('private content lists, real signed packages, updates and revocation reuse the existing login', async t => {
  let now = Date.now();
  const client = await startGateway(t, { now: () => now });
  seedPrivateContent(client.config);
  let res = await client.request('/v2/operation-platform/market/skill/list', { method: 'POST', body: '{}' });
  assert.equal(res.status, 401);
  const auth = await completeLogin(client);
  res = await client.request('/portal/operation-platform/market/expert/list', post(auth.accessToken));
  assert.equal(res.status, 200);
  const experts = (await payload(res)).data.items;
  assert.equal(experts.length, 1); assert.equal(experts[0].version, '1.0.0');
  assert.ok(experts[0].display_name_zh.includes('私有测试专家'));
  res = await client.request('/v2/operation-platform/market/skill/download-url', { ...post(auth.accessToken), body: JSON.stringify({ skill_id: 'private-checklist', version: '1.0.0' }) });
  assert.equal(res.status, 200);
  const download = (await payload(res)).data.download_url;
  assert.ok(download.startsWith(client.config.publicUrl + '/content/packages/skill/'));
  res = await fetch(download); assert.equal(res.status, 200);
  const bytes = Buffer.from(await res.arrayBuffer());
  assert.equal(bytes.readUInt32LE(0), 0x04034b50);
  const record = client.app.catalog.get('skill', 'private-checklist');
  assert.equal(createHash('sha256').update(bytes).digest('hex'), record.sha256);
  const etag = res.headers.get('etag');
  res = await fetch(download, { method: 'HEAD' }); assert.equal(res.status, 200);
  assert.equal(Number(res.headers.get('content-length')), bytes.length);
  res = await fetch(download, { headers: { Range: 'bytes=0-3' } }); assert.equal(res.status, 206);
  assert.equal(Buffer.from(await res.arrayBuffer()).readUInt32LE(0), 0x04034b50);
  res = await fetch(download, { headers: { 'If-None-Match': etag } }); assert.equal(res.status, 304);
  const altered = new URL(download); altered.searchParams.set('signature', 'x'.repeat(43));
  res = await fetch(altered); assert.equal(res.status, 401);
  res = await client.request('/connector-agent-plugins/connector-plugins.zip'); assert.equal(res.status, 200);
  const firstConnectorTag = res.headers.get('etag'); await res.arrayBuffer();
  seedPrivateContent(client.config, { version: '1.1.0' });
  res = await client.request('/connector-agent-plugins/connector-plugins.zip', { headers: { 'If-None-Match': firstConnectorTag } });
  assert.equal(res.status, 200); assert.notEqual(res.headers.get('etag'), firstConnectorTag); await res.arrayBuffer();
  res = await client.request('/v2/operation-platform/market/skill/get-by-ids', { ...post(auth.accessToken), body: JSON.stringify({ skill_ids: ['private-checklist'] }) });
  assert.equal(res.status, 200); assert.equal((await payload(res)).data.skills[0].version, '1.1.0');
  res = await fetch(download); assert.equal(res.status, 200); await res.arrayBuffer();
  client.app.store.revoke(auth.refreshToken);
  res = await fetch(download); assert.equal(res.status, 401);
  const next = await completeLogin(client);
  res = await client.request('/v2/operation-platform/market/skill/download-url', { ...post(next.accessToken), body: JSON.stringify({ skill_id: 'private-checklist' }) });
  const expiring = (await payload(res)).data.download_url;
  now += 901000;
  res = await fetch(expiring); assert.equal(res.status, 401);
  assert.ok(!JSON.stringify(client.logs).includes(new URL(download).searchParams.get('signature')));
  assert.ok(!JSON.stringify(client.logs).includes(auth.accessToken));
});

test('catalog ACLs and downlisting restrict both directory metadata and package access', async t => {
  const client = await startGateway(t); seedPrivateContent(client.config);
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wb-content-acl-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'SKILL.md'), '---\nname: restricted\ndescription: private fixture\n---\nRestricted test content.\n');
  client.app.catalog.publish({ kind: 'skill', id: 'restricted', name: 'Restricted', version: '1.0.0', sourceDir: root,
    categoryId: 'restricted', metadata: { allowedUsers: ['some-other-user'] } });
  const auth = await completeLogin(client);
  let res = await client.request('/v2/operation-platform/market/skill/list', post(auth.accessToken));
  const listing = await payload(res);
  assert.ok(!JSON.stringify(listing).includes('Restricted'));
  res = await client.request('/v2/operation-platform/market/skill/download-url', { ...post(auth.accessToken), body: JSON.stringify({ skill_id: 'restricted' }) });
  assert.equal(res.status, 404);
  res = await client.request('/content/packages/skill/restricted/1.0.0', { headers: { Authorization: 'Bearer ' + auth.accessToken } });
  assert.equal(res.status, 403);
  res = await client.request('/v2/operation-platform/market/skill/download-url', { ...post(auth.accessToken), body: JSON.stringify({ skill_id: 'private-checklist' }) });
  const download = (await payload(res)).data.download_url;
  client.app.catalog.setEnabled('skill', 'private-checklist', false);
  res = await fetch(download); assert.equal(res.status, 404);
  res = await client.request('/content/packages/skill/restricted/1.0.0%2F..'); assert.equal(res.status, 400);
  res = await client.request('/workbuddy/expert-marketplace/expert_center.json'); assert.equal(res.status, 200);
  const manifest = await res.json();
  assert.equal(manifest.experts.length, 1); assert.ok(!JSON.stringify(manifest).includes('signature'));
});
